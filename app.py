@st.cache_data(show_spinner="Construyendo matrices de pesos espaciales...")
def build_spatial_weights(_gdf, k=5, alpha=0.55):
    """Queen + KNN combinados, row-standardized."""
    w_q = Queen.from_dataframe(_gdf, ids=_gdf["id"].tolist())
    w_k = KNN.from_dataframe(_gdf, k=k, ids=_gdf["id"].tolist())
    w_q.transform = "r"
    w_k.transform = "r"

    ids = w_q.id_order
    Wq, Wk = w_q.full()[0], w_k.full()[0]
    Wc = alpha*Wq + (1-alpha)*Wk
    rs = Wc.sum(axis=1, keepdims=True)
    rs[rs == 0] = 1.0
    Wc = Wc / rs

    neigh, wts = {}, {}
    for i, idi in enumerate(ids):
        mask = Wc[i] > 1e-8
        neigh[idi] = [ids[j] for j in np.where(mask)[0]]
        wts[idi] = Wc[i, mask].tolist()
    w = W(neigh, wts)
    w.transform = "r"
    return w, w_q, w_k

