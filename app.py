# 5. ESTIMACIÓN S2SLS (Spatial Durbin)
# =============================================================================
def estimate_s2sls_sdm(panel_sp, w, dep, exog_l1, wy_contemp):
    y = panel_sp[dep].values.astype(float)
    X_cols = exog_l1 + [c for c in wy_contemp if c != f"W_{dep}"]
    X = panel_sp[X_cols].values.astype(float)
    name_y = dep
    name_x = X_cols

    try:
        model = GM_Lag(
            y, X, w=w, name_y=name_y, name_x=name_x,
            name_w="W", name_ds="Nariño", robust="white"
        )
        return model
    except Exception as e:
        X_sm = sm.add_constant(panel_sp[X_cols + [f"W_{dep}"]])
        return sm.OLS(y, X_sm).fit(cov_type="HC1")

def compute_spatial_effects(model, w, is_gml=True):
    effects = {}
    try:
        if is_gml and hasattr(model, "rho"):
            rho = float(model.rho)
            n = w.n
            Wmat = w.full()[0]
            S = np.eye(n)
            term = np.eye(n)
            for k in range(1, 6):
                term = rho * (term @ Wmat)
                S = S + term
            direct = np.mean(np.diag(S))
            total = S.sum(axis=1).mean()
            indirect = total - direct
            effects["rho"] = {"direct": direct, "indirect": indirect, "total": total, "rho": rho}
        if hasattr(model, "betas"):
            b = np.asarray(model.betas).flatten()
            names = ["CONSTANT"] + list(model.name_x) if hasattr(model, "name_x") else [f"x{i}" for i in range(len(b))]
            for i, name in enumerate(names):
                if i == 0:
                    continue
                effects[name] = {"coef": float(b[i])}
        elif hasattr(model, "params"):
            for name, val in model.params.items():
                effects[name] = {"coef": float(val)}
    except Exception:
        pass
    return effects

