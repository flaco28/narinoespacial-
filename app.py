@st.cache_data(show_spinner="Construyendo panel espacial + rezagos...")
def build_spatial_panel(_panel, _w, vars_y=("Y1_luces", "Y2_empleo", "Y3_ndvi")):
    """Alinea panel, calcula W·Y por fecha y rezagos temporales L1."""
    panel = _panel.sort_values(["id", "fecha"]).copy()
    ids_order = _w.id_order

    pieces = []
    for fecha, grp in panel.groupby("fecha", sort=False):
        g = grp.set_index("id").reindex(ids_order)
        for v in vars_y:
            y = g[v].fillna(g[v].mean()).values.astype(float)
            g[f"W_{v}"] = lag_spatial(_w, y)
        pieces.append(g.reset_index())
    sp = pd.concat(pieces, ignore_index=True)
    sp = sp.sort_values(["id", "fecha"])

    lag_cols = list(vars_y) + [f"W_{v}" for v in vars_y]
    for c in lag_cols:
        sp[f"{c}_L1"] = sp.groupby("id", sort=False)[c].shift(1)

    sp = sp.dropna().reset_index(drop=True)
    return sp

