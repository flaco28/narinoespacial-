        for ti, d in enumerate(dates):
            records.append({
                "id": row["id"], "municipio": row["municipio"], "fecha": d,
                "Y1_luces": y1[ti], "Y2_empleo": y2[ti], "Y3_ndvi": y3[ti]
            })
