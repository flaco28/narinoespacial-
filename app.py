@st.cache_data(show_spinner="Calculando LISA...")
def compute_lisa(_gdf_panel, _w, vars_y=("Y1_luces", "Y2_empleo", "Y3_ndvi")):
    gdf_l = _gdf_panel.set_index("id").reindex(_w.id_order).reset_index()
    for v in vars_y:
        y = gdf_l[v].values.astype(float)
        li = Moran_Local(y, _w, permutations=399)
        q = li.q.copy()
        q[li.p_sim >= 0.05] = 0
        gdf_l[f"LISA_{v}"] = q
    return gdf_l

