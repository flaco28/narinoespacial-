@st.cache_data(show_spinner="Generando panel calibrado...")
def build_calibrated_panel(_gdf, start="2016-01-01", end="2023-12-01"):
    """Genera panel mensual balanceado con patrones realistas de Nariño."""
    dates = pd.date_range(start, end, freq="MS")
    n_t = len(dates)
    high_l = _gdf["municipio"].str.contains("PASTO|IPIALES|TUMACO|TÚQUERRES|LA UNIÓN", case=False, na=False)
    high_n = _gdf["municipio"].str.contains("SANDONÁ|CONSACÁ|YACUANQUER|FUNES|TANGUA|BUESACO|LA FLORIDA", case=False, na=False)

    records = []
    t = np.arange(n_t)
    for i, row in _gdf.iterrows():
        bl = 9.5 if high_l.iloc[i] else np.random.uniform(0.4, 3.8)
        bn = 0.74 if high_n.iloc[i] else np.random.uniform(0.42, 0.66)
        be = 14500 if high_l.iloc[i] else np.random.uniform(700, 4800)
        y1 = np.maximum(0.05, bl + 0.012*t + 1.1*np.sin(2*np.pi*t/12) + np.random.normal(0, 0.65, n_t))
